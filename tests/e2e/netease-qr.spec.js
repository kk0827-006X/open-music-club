const { test, expect }=require('@playwright/test')
const { generateSync }=require('otplib')
const { QRADMIN }=require('./fixtures')
const { graphicsProfile }=require('./graphics-profile')
const origin='http://127.0.0.1:4317'
async function post(client,url,data={}){const csrf=await client.get('/api/security/csrf-token');return client.post(url,{headers:{Origin:origin,'X-CSRF-Token':(await csrf.json()).csrfToken},data})}
test('管理员完成网站2FA后扫码连接，关闭停止轮询，重新进入可退出且不影响网站登录',async({page},info)=>{
  const errors=[],responses=[],polls=[],phases=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('request',request=>{if(request.url().endsWith('/api/admin/netease-session/qr/check'))polls.push(request)})
  page.on('response',async response=>{if(response.url().includes('/api/admin/netease-session')){try{const text=await response.text();responses.push(text);if(response.url().endsWith('/qr/check'))phases.push(JSON.parse(text).state)}catch{}}})
  await page.route('https://*.music.126.net/**',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"/>'}))
  await page.route('**/assets/scene-*.js*',route=>{const url=new URL(route.request().url());if(url.searchParams.has('acceptance-original'))return route.continue();url.searchParams.set('acceptance-original','1');return route.fulfill({contentType:'application/javascript',body:graphicsProfile(url.href)})})
  expect((await post(page.request,'/api/auth/login',QRADMIN)).status()).toBe(200)
  const setup=await (await post(page.request,'/api/auth/2fa/setup',{password:QRADMIN.password})).json()
  expect((await post(page.request,'/api/auth/2fa/confirm',{code:generateSync({secret:setup.secret})})).status()).toBe(200)
  await page.goto('/user')
  await expect(page.locator('[data-user-page]')).toBeVisible()
  const open=async()=>{await page.locator('[data-nav="settings"]').click();await page.locator('[data-settings-category="account"]').click();await page.locator('[data-settings-netease]').click();await expect(page.locator('[data-netease-account-panel]')).toBeVisible()}
  await open()
  await expect(page.locator('[data-netease-connection]')).toContainText('仅保存在内存')
  await page.locator('[data-netease-qr-start]').click()
  await expect(page.locator('.netease-login-qr')).toBeVisible()
  await page.screenshot({path:info.outputPath('netease-qr-light.png')})
  await page.evaluate(()=>document.documentElement.dataset.theme='dark')
  await page.screenshot({path:info.outputPath('netease-qr-dark.png')})
  await page.evaluate(()=>document.documentElement.dataset.theme='light')
  await expect.poll(()=>phases.slice()).toContain('waiting')
  await expect.poll(()=>phases.slice()).toContain('confirming')
  await expect(page.locator('[data-netease-connection]')).toContainText('已连接')
  await expect(page.locator('.netease-login-qr')).toHaveCount(0)
  await page.locator('[data-netease-qr-start]').click()
  await expect(page.locator('.netease-login-qr')).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await page.locator('.netease-login-qr').scrollIntoViewIfNeeded()
  await expect(page.locator('.netease-login-qr')).toBeInViewport()
  await page.screenshot({path:info.outputPath('netease-qr-mobile.png')})
  const cancelled=page.waitForResponse(response=>response.url().endsWith('/api/admin/netease-session/qr/cancel'))
  await page.locator('[data-settings-close]').click()
  expect((await cancelled).status()).toBe(200)
  const before=polls.length
  await page.waitForTimeout(6500)
  expect(polls.length).toBe(before)
  await page.setViewportSize({width:1440,height:1000})
  await open()
  await expect(page.locator('[data-netease-connection]')).toContainText('已连接')
  await page.locator('[data-netease-logout]').click()
  await expect(page.locator('[data-netease-connection]')).toContainText('未连接')
  expect((await (await page.request.get('/api/auth/me')).json()).authenticated).toBe(true)
  expect(await page.evaluate(()=>Object.keys(localStorage).some(key=>/netease|cookie|qr-ticket/i.test(key)))).toBe(false)
  expect(responses.join('\n')).not.toContain('isolated-qr-acceptance-cookie')
  expect(errors).toEqual([])
})
