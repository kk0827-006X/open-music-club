const { test, expect } = require('@playwright/test')
const { generateSync } = require('otplib')
const fs = require('node:fs')
const path = require('node:path')
const { PASSWORD } = require('./fixtures')
const { graphicsProfile } = require('./graphics-profile')
const origin='http://127.0.0.1:4317'
async function post(client,url,data) {
  const csrf=await client.get('/api/security/csrf-token')
  return client.post(url,{headers:{Origin:origin,'X-CSRF-Token':(await csrf.json()).csrfToken},data})
}
function resetLink() {
  const messages=JSON.parse(fs.readFileSync(path.resolve(__dirname,'../../artifacts/e2e/mailbox.json'),'utf8'))
  return messages.filter(m=>m.to===PASSWORD.email && m.subject.includes('重置密码')).at(-1)?.text.match(/http:\/\/127\.0\.0\.1:4317\/reset-password#token=[\w-]{43}/)?.[0] || ''
}
async function fillPassword(page,password,oldPassword,code) {
  if(oldPassword!==undefined) await page.getByLabel('原密码',{exact:true}).fill(oldPassword)
  await page.getByLabel('新密码',{exact:true}).fill(password)
  await page.getByLabel('确认新密码',{exact:true}).fill(password)
  if(code) { await page.getByLabel('使用一次性恢复码').check(); await page.getByLabel('恢复码',{exact:true}).fill(code) }
  await page.getByRole('button',{name:'确认更新密码',exact:true}).click()
}
test('真实隔离账号：设置修改密码、旧设备失效、登录页邮件找回与2FA恢复码重置',async({page,browser},info)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.route('https://*.music.126.net/**',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"/>'}))
  await page.route('**/assets/scene-*.js*',route=>{const url=new URL(route.request().url());if(url.searchParams.has('acceptance-original')) return route.continue();url.searchParams.set('acceptance-original','1');return route.fulfill({contentType:'application/javascript',body:graphicsProfile(url.href)})})
  const other=await browser.newContext({baseURL:origin})
  const changed='Changed-password-2026!', reset='Reset-password-2026!'
  try {
    await page.goto('/login?next=%2Fuser')
    await page.getByLabel(/邮箱地址/).fill(PASSWORD.email);await page.locator('#password').fill(PASSWORD.password)
    await page.getByRole('button',{name:'验证身份',exact:true}).click()
    await expect(page.locator('[data-user-page]')).toBeVisible()
    expect((await post(other.request,'/api/auth/login',PASSWORD)).status()).toBe(200)
    const setup=await (await post(page.request,'/api/auth/2fa/setup',{password:PASSWORD.password})).json()
    const confirmation=await post(page.request,'/api/auth/2fa/confirm',{code:generateSync({secret:setup.secret})})
    const codes=(await confirmation.json()).recoveryCodes
    expect(codes).toHaveLength(10)
    await page.locator('[data-nav="settings"]').click();await page.locator('[data-settings-category="account"]').click();await page.locator('[data-settings-password]').click()
    await page.screenshot({path:info.outputPath('settings-password-light.png')})
    await page.setViewportSize({width:390,height:844})
    await page.getByRole('button',{name:'确认更新密码',exact:true}).scrollIntoViewIfNeeded()
    await expect(page.getByRole('button',{name:'确认更新密码',exact:true})).toBeInViewport()
    await page.screenshot({path:info.outputPath('settings-password-mobile.png')})
    await page.setViewportSize({width:1440,height:1000})
    await fillPassword(page,changed,'Wrong-password1!')
    await expect(page.locator('[data-password-panel] [role="status"]')).toContainText('原密码或两步验证未通过')
    await expect(page.getByLabel('原密码',{exact:true})).toHaveValue('')
    await fillPassword(page,changed,PASSWORD.password,codes[0])
    await expect(page).toHaveURL(/\/login$/)
    await expect(page.locator('[data-login-form]')).toBeVisible()
    expect((await other.request.get('/api/protected')).status()).toBe(401)
    expect((await post(other.request,'/api/auth/login',PASSWORD)).status()).toBe(401)
    await page.locator('[data-forgot-password-open]').click()
    await page.getByLabel('注册邮箱',{exact:true}).fill(PASSWORD.email)
    await page.getByRole('button',{name:'发送重置邮件',exact:true}).click()
    await expect(page.locator('[data-forgot-password-dialog] [role="status"]')).toContainText('如果该邮箱对应可用账号')
    await expect.poll(resetLink).not.toBe('')
    const link=resetLink()
    await page.goto(link)
    await expect(page).toHaveURL(`${origin}/reset-password`)
    await expect(page.locator('[data-global-player]')).toHaveCount(0)
    await fillPassword(page,reset)
    await expect(page.locator('[data-password-panel] [role="status"]')).toContainText('原密码或两步验证未通过')
    await fillPassword(page,reset,undefined,codes[1])
    await expect(page.locator('[data-password-panel] [role="status"]')).toContainText('密码已更新')
    expect((await (await page.request.get('/api/auth/me')).json()).authenticated).toBe(false)
    await page.screenshot({path:info.outputPath('password-reset-complete.png')})
    await page.goto(link)
    await fillPassword(page,'Replay-password-2026!',undefined,codes[2])
    await expect(page.locator('[data-password-panel] [role="status"]')).toContainText('链接失效')
    await page.goto('/login?next=%2Fuser')
    await page.getByLabel(/邮箱地址/).fill(PASSWORD.email);await page.locator('#password').fill(reset)
    await page.getByRole('button',{name:'验证身份',exact:true}).click()
    await expect(page.locator('[data-login-factor-dialog]')).toBeVisible()
    await page.getByLabel('使用恢复码',{exact:true}).check()
    await page.getByLabel('恢复码',{exact:true}).fill(codes[0])
    await page.getByRole('button',{name:'确认登录',exact:true}).click()
    await expect(page.locator('[data-factor-feedback]')).toContainText('验证失败')
    await page.getByLabel('恢复码',{exact:true}).fill(codes[3]);await page.getByRole('button',{name:'确认登录',exact:true}).click()
    await expect(page.locator('[data-user-page]')).toBeVisible()
    expect(errors).toEqual([])
  } finally {await other.close()}
})

test('找回入口遇到非JSON代理响应仅显示固定提示，窄屏仍可关闭并归焦',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.route('**/api/security/csrf-token',route=>route.fulfill({status:200,contentType:'text/html',body:'<html>/private/internal SECRET=value</html>'}))
  await page.goto('/login')
  await page.locator('[data-forgot-password-open]').click()
  await page.getByLabel('注册邮箱',{exact:true}).fill('isolated@example.com')
  await page.getByRole('button',{name:'发送重置邮件',exact:true}).click()
  await expect(page.locator('[data-forgot-password-dialog] [role="status"]')).toHaveText('服务响应暂时不可用，请稍后重试')
  await expect(page.locator('[data-forgot-password-dialog]')).not.toContainText('/private/internal')
  await page.getByRole('button',{name:'关闭密码找回',exact:true}).click()
  await expect(page.locator('[data-forgot-password-open]')).toBeFocused()
})
