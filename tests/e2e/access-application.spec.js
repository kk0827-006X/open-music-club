const { test, expect } = require('@playwright/test')
const { generateSync } = require('otplib')
const { REVIEWER, readApplicationLink } = require('./fixtures')
const origin = 'http://127.0.0.1:4317'
async function post(client, path, data) {
  const csrf = await (await client.get('/api/security/csrf-token')).json()
  return client.post(path, { data, headers: { Origin: origin, 'X-CSRF-Token': csrf.csrfToken } })
}

test('申请 → 直接待审核 → 管理员 GUI 审核 → 自设密码激活，隐藏邮箱及凭证', async ({ page, browser }, info) => {
  // 恰好 8 位的合成密码，验证用户可以通过 GUI 设置最短合规密码。
  const email = 'application-ui-candidate@example.com', password = 'Club202!'
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  let verificationRequests = 0
  page.on('request', req => { if (req.url().endsWith('/api/applications/verify-email')) verificationRequests++ })
  await page.goto('/')
  await page.getByRole('button', { name: /点击进入/ }).click()
  const entry = page.getByRole('button', { name: '申请账号', exact: true })
  await entry.click()
  const dialog = page.getByRole('dialog', { name: '申请账号' })
  await expect(dialog.getByLabel('联系邮箱')).toBeFocused()
  await dialog.getByLabel('联系邮箱').fill(email)
  await dialog.getByLabel('昵称').fill('申请界面验收成员')
  await dialog.getByLabel('申请理由（选填）').fill('隔离数据库中的界面验收。')
  const submitted = page.waitForResponse(response => response.url().endsWith('/api/applications') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: '提交申请', exact: true }).click()
  expect((await submitted).status()).toBe(202)
  await expect(dialog.locator('[data-application-feedback]')).toContainText('申请已提交并进入审核')
  await expect(dialog.locator('[data-application-feedback]')).not.toContainText('验证邮件')
  await expect(dialog.locator('[data-application-activation-link]')).toHaveAttribute('href', '/activate')
  await dialog.getByRole('button', { name: '关闭账号申请' }).click()
  await expect(entry).toBeFocused()
  expect(verificationRequests).toBe(0)
  // 旧验证页面只保留兼容说明，不需要也不发送验证请求，且不挂载播放器。
  const documentResponse = await page.goto('/verify-email#token=aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa')
  expect(documentResponse.headers()['cache-control']).toContain('no-store')
  await expect(page.getByRole('heading', { name: '申请流程已简化' })).toBeVisible()
  await expect(page.getByText('无需验证邮箱')).toBeVisible()
  await expect(page.locator('[data-global-player]')).toHaveCount(0)
  expect(page.url()).toBe(`${origin}/verify-email`)
  expect(verificationRequests).toBe(0)
  const adminContext = await browser.newContext({ baseURL: origin })
  try {
    const admin = adminContext.request
    await expect((await post(admin, '/api/auth/login', REVIEWER)).ok()).toBeTruthy()
    expect((await admin.get('/api/admin/applications')).status()).toBe(403)
    const setup = await (await post(admin, '/api/auth/2fa/setup', { password: REVIEWER.password })).json()
    expect((await post(admin, '/api/auth/2fa/confirm', { code: generateSync({ secret: setup.secret }) })).status()).toBe(200)
    const adminPage = await adminContext.newPage()
    const privateResponses = []
    adminPage.on('response', async response => { if (response.url().includes('/api/admin/applications')) privateResponses.push(await response.text()) })
    await expect.poll(async () => {
      const result = await (await admin.get('/api/admin/applications?status=pending')).json()
      return result.applications?.some(item => item.nickname === '申请界面验收成员' && item.canReview)
    }).toBe(true)
    await adminPage.goto('/admin/applications')
    await expect(adminPage.locator('[data-admin-applications]')).toBeVisible()
    await adminPage.getByRole('button', { name: /申请界面验收成员/ }).click()
    await expect(adminPage.getByRole('heading', { name: '申请界面验收成员' })).toBeFocused()
    expect(await adminPage.locator('body').textContent()).not.toContain(email)
    await expect(adminPage.getByRole('button', { name: '通过审核', exact: true })).toBeEnabled()
    await adminPage.screenshot({ path: info.outputPath('admin-review-light.png') })
    await adminPage.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
    await adminPage.screenshot({ path: info.outputPath('admin-review-dark.png') })
    await adminPage.setViewportSize({ width: 390, height: 844 })
    expect(await adminPage.locator('body').evaluate(el => el.scrollWidth <= window.innerWidth)).toBe(true)
    await adminPage.screenshot({ path: info.outputPath('admin-review-mobile.png') })
    await adminPage.getByRole('button', { name: '通过审核', exact: true }).click()
    await expect(adminPage.getByRole('dialog', { name: '确认通过申请？' })).toBeVisible()
    await adminPage.getByRole('button', { name: '确认决定', exact: true }).click()
    await expect(adminPage.locator('.application-feedback')).toContainText('激活邮件已入队')
    await adminPage.getByRole('button', { name: '待激活', exact: true }).click()
    await expect(adminPage.getByRole('button', { name: /申请界面验收成员/ })).toBeVisible()
    await adminPage.getByRole('button', { name: /申请界面验收成员/ }).click()
    await expect(adminPage.getByText('激活邮件', { exact: true })).toBeVisible()
    // GUI 补发按钮与确认弹窗存在；真实等待 60 秒冷却由组件测试覆盖，不在此长时间阻塞。
    await adminPage.getByRole('button', { name: '重发激活邮件', exact: true }).click()
    await expect(adminPage.getByRole('dialog', { name: '确认重发激活邮件？' })).toBeVisible()
    await expect(adminPage.getByRole('dialog', { name: '确认重发激活邮件？' })).toContainText('旧链接会立即失效')
    await adminPage.keyboard.press('Escape')
    await expect(adminPage.getByRole('dialog', { name: '确认重发激活邮件？' })).not.toBeVisible()
    for (const body of privateResponses) expect(body).not.toMatch(/application-ui-candidate@example.com|#token=|ciphertext|password_hash/)
    await expect.poll(() => readApplicationLink(email, 'activate')).not.toBe('')
    await page.goto(readApplicationLink(email, 'activate'))
    await expect(page.getByLabel('新密码', { exact: true })).toBeVisible()
    await expect(page.getByText('密码需为8～72位，包含大写字母、小写字母、数字和符号。', { exact: true })).toBeVisible()
    expect(page.url()).toBe(`${origin}/activate`)
    await expect(page.locator('[data-global-player]')).toHaveCount(0)
    await page.getByRole('button', { name: '设置密码并激活', exact: true }).hover()
    await expect(page.getByRole('button', { name: '设置密码并激活', exact: true }).locator('span')).toHaveCSS('z-index', '1')
    await page.getByLabel('新密码', { exact: true }).fill(password)
    await page.getByLabel('确认密码', { exact: true }).fill(password)
    await page.getByRole('button', { name: '设置密码并激活', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('账号已激活')
    expect((await (await page.request.get('/api/auth/me')).json()).authenticated).toBe(false)
    expect((await post(page.request, '/api/auth/login', { email, password })).status()).toBe(200)
    expect((await page.request.get('/api/admin/applications')).status()).toBe(403)
    await page.goto('/admin/applications')
    await expect(page.getByRole('heading', { name: '无权访问申请审核' })).toBeVisible()
    await expect(page.locator('[data-admin-applications]')).toHaveCount(0)
    expect(errors).toEqual([])
    expect(verificationRequests).toBe(0)
  } finally { await adminContext.close() }
})

test('过期激活链接允许自助重发，不泄露邮箱是否存在', async ({ page }) => {
  await page.goto('/activate#token=invalid')
  await expect(page.getByRole('button', { name: '重新发送激活邮件', exact: true })).toBeVisible()
  expect(page.url()).toBe(`${origin}/activate`)
  await page.getByLabel('申请邮箱').fill('unknown-candidate@example.com')
  await page.getByRole('button', { name: '重新发送激活邮件', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('如果该邮箱对应的申请已通过且尚未激活')
  await expect(page.locator('[data-global-player]')).toHaveCount(0)
})
